"""Frozen teaching designs. CSG subtraction, connectivity, and geometry-only solver.
No solution ordering is consumed by the game. Run to regenerate LevelData.js.
"""
import json,itertools
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
BARS=[([-3,-1,-1],[3,1,1]), ([-.5,-3,-.5],[.5,3,.5]), ([-.25,-.25,-3],[.25,.25,3]), ([-3,-.125,1.875],[3,.125,2.125])]
AXES=['x','y','z','x']
NAMES=['承榫横梁','穿榫纵梁','中心锁销','横向止退销']
def intersect(a,b): return all(a[0][i]<b[1][i]-1e-8 and b[0][i]<a[1][i]-1e-8 for i in range(3))
def subtract(a,b):
 if not intersect(a,b): return [a]
 out=[];lo=a[0][:];hi=a[1][:]
 for i in range(3):
  if lo[i]<b[0][i]:
   h=hi[:];h[i]=b[0][i];out.append((lo[:],h));lo[i]=b[0][i]
  if hi[i]>b[1][i]:
   l=lo[:];l[i]=b[1][i];out.append((l,hi[:]));hi[i]=b[1][i]
 return out
def connected(bs):
 seen={0}
 while True:
  old=len(seen)
  for i,a in enumerate(bs):
   for j in list(seen):
    b=bs[j]; widths=[min(a[1][k],b[1][k])-max(a[0][k],b[0][k]) for k in range(3)]
    if min(widths)>=-1e-8 and sum(v>1e-8 for v in widths)>=2: seen.add(i)
  if len(seen)==old:return len(seen)==len(bs)
def sweep_blockers(pieces,i,remaining,sign):
 axis='xyz'.index(AXES[i]);result=[]
 for j in remaining:
  if i==j:continue
  for a in pieces[i]:
   lo=a[0][:];hi=a[1][:]
   if sign>0:hi[axis]+=8
   else:lo[axis]-=8
   if any(intersect((lo,hi),b) for b in pieces[j]):result.append(j);break
 return result
def build(n):
 pieces=[]
 for i in range(n):
  bs=[BARS[i]]
  for hole in BARS[i+1:n]:bs=[part for a in bs for part in subtract(a,hole)]
  assert connected(bs),('disconnected',n,i)
  pieces.append(bs)
 for i,j in itertools.combinations(range(n),2):assert not any(intersect(a,b) for a in pieces[i] for b in pieces[j])
 # Explore EVERY reachable removal subset, checking all choices still lead to completion.
 visited=set();paths={}
 def solve(rem):
  key=tuple(rem)
  if key in visited:return
  visited.add(key)
  if not rem:return
  moves=[(i,s) for i in rem for s in [-1,1] if not sweep_blockers(pieces,i,rem,s)]
  assert moves,('dead end',n,rem)
  paths[str(key)]=[(NAMES[i],s) for i,s in moves]
  for i,s in moves:solve([j for j in rem if j!=i])
 solve(list(range(n)))
 initial=[i for i in range(n) if any(not sweep_blockers(pieces,i,list(range(n)),s) for s in [-1,1])]
 assert initial==[n-1],initial
 return pieces,paths
levels=[];reports=[]
for n,title,goal in [(2,'01 穿榫入门 · 两件','观察横梁的贯通卯眼。纵梁穿过卯眼，先沿其长轴退出，再拆横梁。'),(3,'02 交叉锁定 · 三件','纵梁增加销孔，中心锁销穿孔阻挡纵梁。先找锁销，再观察哪件被解锁。'),(4,'03 止退锁定 · 四件','中心锁销增加横孔，由细止退销锁住。逐层解除阻挡，完成四件拆解。')]:
 pieces,paths=build(n)
 levels.append(dict(id='L'+str(n-1),name=title,goal=goal,pieces=[dict(id='p'+str(i+1),name=NAMES[i],axis=AXES[i],boxes=[dict(c=[(a[k]+b[k])/2 for k in range(3)],s=[b[k]-a[k] for k in range(3)]) for a,b in boxes]) for i,boxes in enumerate(pieces)]))
 reports.append(dict(level=n-1,connected=True,zero_overlap=True,all_reachable_states_solvable=True,states=paths))
(ROOT/'LevelData.js').write_text('// Generated by luban/tools/luban_solver.py; visible and collision geometry are identical.\n.pragma library\nvar UNIT = 21\nvar GRID = 6\nvar levels = '+json.dumps(levels,ensure_ascii=False,indent=2)+'\nfunction levelCount(){return levels.length}\nfunction levelAt(i){return levels[i]}\n')
(ROOT/'tests/geometry-result.json').write_text(json.dumps(reports,ensure_ascii=False,indent=2))
print('PASS: connected solids, no overlaps, unique initial key, all reachable removal states solvable (3 levels)')
