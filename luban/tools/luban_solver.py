"""Frozen CSG designs. Regenerate display/collision boxes and independently verify them.

No solution order is loaded by the game. L4/L5 use shoulder pins in offset
keyholes: the centre rail has to slide, reverse and return before removal.
"""
import itertools
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
BARS = [([-3, -1, -1], [3, 1, 1]), ([-.5, -3, -.5], [.5, 3, .5]),
        ([-.25, -.25, -3], [.25, .25, 3]), ([-3, -.125, 1.875], [3, .125, 2.125])]
AXES = ['x', 'y', 'z', 'x']
NAMES = ['承榫横梁', '穿榫纵梁', '中心锁销', '横向止退销']


def intersect(a, b):
    return all(a[0][i] < b[1][i] - 1e-8 and b[0][i] < a[1][i] - 1e-8 for i in range(3))


def subtract(a, b):
    if not intersect(a, b):
        return [a]
    out, lo, hi = [], list(a[0]), list(a[1])
    for i in range(3):
        if lo[i] < b[0][i]:
            h = hi[:]; h[i] = b[0][i]
            out.append((lo[:], h)); lo[i] = b[0][i]
        if hi[i] > b[1][i]:
            l = lo[:]; l[i] = b[1][i]
            out.append((l, hi[:])); hi[i] = b[1][i]
    return out


def piece(pid, name, axis, boxes):
    return dict(id=pid, name=name, axis=axis, boxes=[dict(c=[(a[k] + b[k]) / 2 for k in range(3)],
                   s=[b[k] - a[k] for k in range(3)]) for a, b in boxes])


def teaching(n, title, goal):
    pieces = []
    for i in range(n):
        bs = [BARS[i]]
        for hole in BARS[i + 1:n]:
            bs = [part for a in bs for part in subtract(a, hole)]
        pieces.append(piece('p' + str(i + 1), NAMES[i], AXES[i], bs))
    return dict(id='L' + str(n - 1), name=title, goal=goal, kind='teaching', pieces=pieces)


def offset_lock(lid, length, pin_centres, wide_centres, title):
    # Through-Y slot admits each pin's stem. A wider opening admits its shoulders
    # only after the rail translates. Outer Z rails connect the whole solid.
    slot_limit = length - .5
    holes = [([-slot_limit, -.6, -.2], [slot_limit, .6, .2])]
    for x in wide_centres:
        holes.append(([max(-slot_limit, x - .5), -.6, -.7],
                      [min(slot_limit, x + .5), .6, .7]))
    beam = [([-length, -.5, -1], [length, .5, 1])]
    for hole in holes:
        beam = [part for a in beam for part in subtract(a, hole)]
    pieces = [piece('p1', '偏移双轨梁', 'x', beam)]
    for i, x in enumerate(pin_centres, 2):
        # Three overlapping boxes form one connected shoulder pin.
        boxes = [([x - .25, -3, -.15], [x + .25, 3, .15]),
                 ([x - .2, -.95, -.6], [x + .2, -.75, .6]),
                 ([x - .2, .75, -.6], [x + .2, .95, .6])]
        pieces.append(piece('p' + str(i), '双肩锁销 ' + str(i - 1), 'y', boxes))
    return dict(id=lid, name=title, kind='offset_keyhole',
                goal='观察榫槽与锁肩。尝试部分滑动、换件与反向推回；按真实接触位置拆开整副机关。',
                pieces=pieces)


def main():
    levels = [
        teaching(2, '01 穿榫入门 · 两件', '沿木件长轴尝试 A / B 端，观察贯通榫孔如何限制移动。'),
        teaching(3, '02 交叉锁定 · 三件', '从装配结构寻找接触关系；尝试、观察并解除交叉锁定。'),
        offset_lock('L3', 3, [-1.5, 1.5], [-2.25, 2.25], '03 双肩迷锁 · 观察与推回'),
        offset_lock('L4', 4.5, [-3, -1.5, 1.5, 3], [-3.75, -.75, 2.25], '04 交错锁肩 · 往返解锁'),
        offset_lock('L5', 4.5, [-3, -1.5, 0, 1.5, 3], [-3.75, -.75, 2.25], '05 六件交错 · 分支解谜'),
    ]
    data = json.dumps(levels, ensure_ascii=False, indent=2)
    (ROOT / 'LevelData.js').write_text('// Generated by luban/tools/luban_solver.py; visible and collision geometry are identical.\n'
        '.pragma library\nvar UNIT = 21\nvar GRID = 9\nvar levels = ' + data + '\n'
        'function levelCount(){return levels.length}\nfunction levelAt(i){return levels[i]}\n')
    # A separate program reads only exported boxes; it shares no CSG or move code.
    from verify_geometry import verify_all
    report = verify_all(ROOT / 'LevelData.js')
    (ROOT / 'tests/geometry-result.json').write_text(json.dumps(report, ensure_ascii=False, indent=2))
    print(json.dumps(report['summary'], ensure_ascii=False))


if __name__ == '__main__':
    main()
